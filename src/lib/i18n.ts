export function translateMatch(matchStr: string, lang: Lang): string {
  var parts = matchStr.split(' vs ');
  if (parts.length !== 2) return matchStr;
  var home = translateTeam(parts[0], lang);
  var away = translateTeam(parts[1], lang);
  return home + ' vs ' + away;
}

